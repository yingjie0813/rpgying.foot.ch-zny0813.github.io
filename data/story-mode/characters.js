/* ==========================================================================
   故事模式的角色資料：所有可用的屬性與值
   --------------------------------------------------------------------------
   key 就是章節文本裡 who 欄位寫的名字（who: "老乞丐" → 這裡找 "老乞丐"）。
   「旁白」「系統消息」這類說話者也要寫在這裡。who 沒有寫在這裡時不會出錯，
   會直接用 who 當名字，頭像一樣依序找 portraits.js → 印章（但主控台會警告）。
   "{name}" 是玩家自己，會自動換成玩家取的名字，不需要寫在這裡。

   ■ 一般欄位
     name         顯示的名字（可省略，省略就用 key）
     img          頭像網址；留空 "" → 到 data/portraits.js 用 name 查；還查不到 → 印章頭像
     description  角色簡介（目前沒有用到，先留著給你寫設定）

   ■ 數值（全部選填，格式與 bossData 相同）
     maxHp / hp / atk / def
         有填的才會顯示在右上角的角色資料卡（HP 長條、ATK、DEF）；
         沒填就不顯示。hp 省略時等於 maxHp。
         這些也是這個角色當「戰鬥敵人」時的數值（戰鬥場景的 foeStats 可以覆蓋）。
         玩家說話時右上角顯示「俠客資料」，其他角色顯示「角色資料」。

   ■ 戰鬥用欄位（全部選填，這個角色當敵人時才會用到；格式與 data/bosses.js 完全相同，可直接複製）
     intro               戰鬥開始時顯示的介紹文字（自由戰鬥才用；可用 <br> 與 {name}）
     victoryDescription  玩家贏了時顯示的文字
     defeatDescription   玩家輸了時顯示的文字
     preference          出拳偏好（權重），例如 { scissors: 0.45, rock: 0.15, paper: 0.4 }
                         不寫 = 每種拳一樣機率
     招式                敵人的招式，依拳種分類：
                         招式: {
                             scissors: {
                                 招式一: { 名稱: "", 運氣: "預兆文字", 攻擊: "出招文字", 後果: ["你贏時", "平手時", "你輸時"] },
                                 招式二: { ... }
                             },
                             rock: { ... },
                             paper: { ... }
                         }
                         · 自由戰鬥：依 preference 抽拳種，再從該拳種的招式裡隨機抽一招。
                         · 教學戰鬥：回合沒寫 foeMove 時才使用這裡的招式。
                         · 都沒寫：使用通用招式（戰鬥能進行，但文字很簡單）。

   之後想加欄位（外號、立繪、口頭禪…）直接加，不會影響現有功能。
   ========================================================================== */

