/* ==========================================================================
   故事模式的結局資料
   --------------------------------------------------------------------------
   key 就是結局 id（英文、數字、中文都可以，不要重複）。
   在章節檔裡這樣指向結局（next 這類欄位一定要寫 "ending:" 開頭，只寫結局 id 會被當成找不到）：
     場景：      ending: "結局id"          這個場景的台詞播完後，直接進入該結局
     next/選項： next: "ending:結局id"     （前面要加 ending: ）
     onVisit：   onVisit: { 3: "ending:結局id" }   第 3 次進入這個場景時進入結局
     章節：      next: "ending:結局id"     這一章結束後進入結局
     戰鬥：      onWin / onLose: "ending:結局id"

   每個結局可用的欄位：
     title     結局名稱，必填。直接顯示在總結面板最上面的大標題（想顯示「你個假新人」就寫 title: "你個假新人"）
     comment   （選填）評語，直接顯示在面板的「評語」那一列，不寫就顯示「—」
     friends   （選填）「交好的人」：{ 名字: 旗標名 }，章節裡 set 過那個旗標的人才會列出，依寫的順序顯示。
               例：friends: { "山賊乙": "結拜山賊乙", "村長": ["救了村民", "村長好感"] }
               旗標也可以寫成陣列，全部都 set 過才算。沒有任何人符合就顯示「無」。
               旗標怎麼 set、怎麼取名，請看 ch01.js 開頭的「set 與旗標」教學。
     summary   （選填）標題下方的一句小字。不寫就不顯示
     rows      （選填）總結面板上自己加的統計列（顯示在「擊敗」之後、「最終數值」之前），
               例如 rows: [["旅程","三天兩夜"]]
     bg        （選填）背景（台詞播放時與總結面板都用這張）。可用：
               title road river temple inn arena1 market bamboo field bridge arena2
               cliff stones falls summit arena3 end endDark bazaar（江湖市集）yamen（監獄衙門）
               不寫 = "end"
     lines     （選填）結局的台詞陣列，格式與場景的 lines 完全相同：
               { who: "旁白", text: "文字，可用 <br> 換行與 {name}" }
               who 要寫在 characters.js（"{name}" 是玩家自己）。
               每句還可以寫 set / effect（見章節檔開頭的說明）。
     之後想加欄位直接加，不會出錯。

   結局流程：先播 lines（沒寫就直接進總結），然後出現總結面板（和通關、倒下時的結算畫面同一種：
   標題、評語、交好的人、擊敗、（你加的 rows）、最終數值、結局收集 已達成/總數）。
   「擊敗」不用寫：這一局打贏的戰鬥敵人會自動記下來，沒有就顯示「無」。標題與評語就是這個檔案裡寫的字，程式不會改；
   面板上可以「再來一局」或「回到開始畫面」。結局會記錄為「已達成」（存在瀏覽器 localStorage），
   開始畫面的「故事」卡片也會顯示「結局 已達成/總數」。總數 = 這個檔案裡結局的數量。
   ========================================================================== */

export const endings = {

    /* ↓ 範例結局：之後請改成自己的內容，或整段刪掉（刪掉後總數會跟著少一個） */
    "假新人": {
        title: "假新人",
        kind: "你個假新人??",
        bg: "end",
        lines: [
            { who: "旁白", text: "這是範例結局。請在 data/story-mode/endings.js 改成自己的內容。" }
        ]
    }

};
